"""Build sources.js from cached metabot.gg soul pages.

    build.py <cache/pages> <pets.js>  > sources.js

A soul page ("Soul: <pet> (Bound)") lists the monsters that drop the soul
(level, chance, zone and map, nearest Kibelisk) and the chests that hold it.
Pages are matched to the plugin's pet ids by English name; unmatched names
are reported on stderr.
"""
import html
import json
import os
import re
import sys


def text(s):
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", s))).strip()


def parse(path):
    t = open(path, errors="ignore").read()
    m = re.search(r"<h1[^>]*>(.*?)</h1>", t, re.S)
    title = text(m.group(1)) if m else ""
    drops, chests = [], []
    for row in re.finditer(r'<li id="where-(drop|box)-[^"]*".*?</li>', t, re.S):
        kind, li = row.group(1), row.group(0)
        who = re.search(r'<a [^>]*href="[^"]+"[^>]*>.*?<span[^>]*>([^<]+)</span></a>\s*<span[^>]*>([^<]*)</span>', li, re.S)
        if not who:
            continue
        subs = [text(s) for s in re.findall(r'<div class="where-module[^"]*__(?:sub|kisk)[^"]*">(.*?)</div>', li, re.S)]
        entry = {"name": html.unescape(who.group(1)).strip(), "chance": html.unescape(who.group(2)).strip()}
        if kind == "drop":
            for s in subs:
                if s.startswith("Lv."):
                    entry["level"] = s[3:].strip()
                elif s.startswith("Nearest Kibelisk:"):
                    entry["kibelisk"] = s.split(":", 1)[1].strip()
                elif s:
                    entry["where"] = s
            drops.append(entry)
        else:
            if subs:
                entry["from"] = "; ".join(subs)
            chests.append(entry)
    return title, drops, chests


def key(name):
    return re.sub(r"[^a-z0-9]", "", name.lower())


def number_teleports(drops, teleports):
    """Each drop's nearest Kibelisk gets the number the in-game map gives it
    (teleports.json, by region), where that region's list is known."""
    for d in drops:
        name = d.get("kibelisk", "").split(" · ")[0]
        parts = d.get("where", "").split(" · ")
        region = parts[1] if len(parts) > 2 else ""
        # A number, or "17/18" where the in-game list can't tell two apart.
        number = teleports.get(region, {}).get(name)
        if number:
            d["teleport"] = number


def main():
    pages, pets_js = sys.argv[1], sys.argv[2]
    here = os.path.dirname(os.path.abspath(__file__))
    teleports = {k: v for k, v in json.load(open(os.path.join(here, "teleports.json"))).items() if not k.startswith("_")}
    names = {}
    for pet_id, en in re.findall(r'^\s*(\d+): \{ "en": "((?:[^"\\]|\\.)*)"', open(pets_js).read(), re.M):
        names.setdefault(key(json.loads(f'"{en}"')), []).append(int(pet_id))
    out, unmatched = {}, []
    for fn in sorted(os.listdir(pages)):
        if not fn.endswith(".html"):
            continue
        title, drops, chests = parse(os.path.join(pages, fn))
        number_teleports(drops, teleports)
        pet = re.sub(r"^Soul:\s*", "", re.sub(r"\s*\(Bound\)\s*$", "", title))
        ids = names.get(key(pet))
        if not ids:
            unmatched.append(pet or fn)
            continue
        entry = {"title": title, "url": "https://metabot.gg/en/aion-2/items/" + fn[: -len(".html")], "drops": drops, "chests": chests}
        for pet_id in ids:
            out[pet_id] = entry
    for pet in unmatched:
        print(f"no pet named {pet!r}", file=sys.stderr)
    print(f"{len(out)} pets with sources, {len(unmatched)} pages unmatched", file=sys.stderr)
    print("// Where each pet's souls come from, keyed by pet id: the monsters that")
    print("// drop them and the chests that hold them. From metabot.gg (each entry's")
    print("// `url` is its page; their terms ask for that link). Generated by")
    print("// tools/metabot-souls/update.sh; don't edit by hand.")
    print("const PET_SOURCES = " + json.dumps(out, ensure_ascii=False, indent=1, sort_keys=True) + ";")


main()
