"""Build the Cooldowns plugin's selfbuffs.js: the buffs each class's skills put on yourself.

    python tools/cooldowns/build_self_buffs.py --tables <...>/Output/AION2/Content/Data/Table

Reads the game's Skill, SkillEffect and SkillEffectFilter tables and the
plugin's own skills.js (built by build_skills.py, whose buffs it keeps to):

  Skill.json            a class skill (SkillString_Key STR_SKILL_PC_<CLASS>_, any
                        type: actives and the passives' own "System" skills)
                        lists SkillEffectTimeDataList: (filter, effect group)
  SkillEffectFilter     EffectRangeType Self, or friendly targets (a party buff
                        reaches its caster too)
  SkillEffect           Abnormal / Abnormal_True rows of that group: the third
                        value is the abnormal (buff) id it applies

A buff comes in many ids (one per skill level, rank or variant), all with one
name and icon: each class's are grouped by the two, so the Buffs tab lists one
row for each, before it has ever been on you.

Writes plugins/cooldowns/selfbuffs.js: window.COOLDOWN_SELF_BUFFS =
{ class prefix: [[skill group or 0, [abnormal ids]], ...] }.
"""

import argparse
import json
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
OUT = ROOT / "plugins" / "cooldowns"
CLASSES = {"GLADIATOR": "11", "TEMPLAR": "12", "ASSASSIN": "13", "RANGER": "14", "SORCERER": "15",
           "ELEMENTALIST": "16", "CLERIC": "17", "CHANTER": "18", "FIGHTER": "19"}
APPLIES = {"ESkillEffectType::Abnormal", "ESkillEffectType::Abnormal_True"}


def rows(tables, name):
    return json.loads((tables / name).read_text(encoding="utf-8"))["Properties"]["Data"]


def plugin_data():
    js = (OUT / "skills.js").read_text(encoding="utf-8")
    return json.loads(js[js.index("{"):js.rindex("}") + 1])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tables", required=True, type=Path)
    args = ap.parse_args()

    data = plugin_data()
    buffs = data["buffs"]
    groups = {cls: {s["g"] for s in c["skills"]} for cls, c in data["classes"].items()}
    filters = {r["ID"]["Value"]: r for r in rows(args.tables, "SkillEffectFilter.json")}
    effects = defaultdict(list)
    for e in rows(args.tables, "SkillEffect.json"):
        effects[e["SkillEffectGroupId"]["Value"]].append(e)

    # class -> (name, icon) -> {"ids": set, "g": first cooldown group seen}
    families = {cls: {} for cls in CLASSES.values()}
    for r in rows(args.tables, "Skill.json"):
        m = re.match(r"STR_SKILL_PC_([A-Z]+)_", r["SkillString_Key"])
        if not m or m.group(1) not in CLASSES:
            continue
        cls = CLASSES[m.group(1)]
        # The skill's cooldown group; a passive's "System" skill (Doom Shield's
        # 12070007) goes by its base id's, when that is a skill with one.
        sid = r["ID"]["Value"]
        group = next((g for g in (r.get("GroupCoolTimeId") or 0, sid - sid % 10000) if g in groups.get(cls, ())), 0)
        found = []
        for t in r.get("SkillEffectTimeDataList") or []:
            f = filters.get(t["SkillEffectFilterId"]["Value"])
            if not f or not (f["EffectRangeType"] == "ESkillEffectRangeType::Self" or f["bRelationshipFriendly"]):
                continue
            for e in effects.get(t["SkillEffectGroupId"]["Value"], []):
                v = e["EffectValueList"]
                if e["EffectType"] in APPLIES and len(v) > 2 and v[2] in buffs:
                    found.append(v[2])
        toggle = (r.get("ToggleOnAbnormalId") or {}).get("Value")
        if toggle and str(toggle) in buffs:
            found.append(str(toggle))
        for a in found:
            fam = families[cls].setdefault((buffs[a]["t"], buffs[a]["icon"]), {"ids": set(), "g": 0})
            fam["ids"].add(int(a))
            if group and not fam["g"]:
                fam["g"] = group

    out = {cls: sorted(([f["g"], sorted(f["ids"])] for f in fams.values()), key=lambda x: x[1][0])
           for cls, fams in sorted(families.items())}
    js = ("// Generated by tools/cooldowns/build_self_buffs.py from the game's Skill,\n"
          "// SkillEffect and SkillEffectFilter tables. Do not edit.\n"
          "// The buffs each class's skills put on yourself, by class prefix: [skill group\n"
          "// (0: a passive's, or no cooldown), [abnormal ids, one buff: one name and icon]].\n"
          "window.COOLDOWN_SELF_BUFFS = " + json.dumps(out, separators=(",", ":")) + ";\n")
    (OUT / "selfbuffs.js").write_text(js, encoding="utf-8", newline="\n")
    print("buffs per class:", {cls: len(v) for cls, v in out.items()})


if __name__ == "__main__":
    main()
